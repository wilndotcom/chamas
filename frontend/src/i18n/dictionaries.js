/**
 * Interface translations.
 *
 * English is the source of truth: every key must exist here, and it is also what
 * an untranslated key falls back to. That way a missing Kiswahili string shows
 * readable English instead of a raw key or a blank.
 *
 * Terminology is fixed deliberately rather than word-for-word, because these words
 * are printed in the same room as the books:
 *   - member      -> wanachama  (not "wanafunzi", which means learners)
 *   - contribution-> mchango    (singular of michango)
 *   - balance     -> salio
 *   - welfare fund-> hazina ya wafaahamu
 *   - outstanding -> bado iliyolipwa
 *   - loan        -> mkopo (plural mikopo)
 *
 * Placeholders use {name} and are substituted by t(); see i18n/I18nContext.jsx.
 */

